#!/usr/bin/env python3
"""Build src/webui_html.h: web interface and English texts, gzip-compressed.

Source files:  src/webui.html (German; @FW_VERSION@ is replaced) and
               tools/webui_en.py (English texts).
The browser unpacks gzip itself, so the cube sends about a quarter of the bytes.
tools/check.py unpacks the arrays again and compares them with the sources.

    python3 tools/webui_build.py
"""
from pathlib import Path
import gzip, re, importlib.util

ROOT = Path(__file__).resolve().parents[1]


def version():
    return re.search(r'#define FW_VERSION "([^"]+)"', (ROOT / 'src/Version.h').read_text()).group(1)


def html():
    return (ROOT / 'src/webui.html').read_text().replace('@FW_VERSION@', version())


def english():
    spec = importlib.util.spec_from_file_location('webui_en', ROOT / 'tools/webui_en.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.js()


def pack(text):
    return gzip.compress(text.encode('utf-8'), compresslevel=9, mtime=0)


def array(name, data):
    rows = [', '.join(f'0x{b:02x}' for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    return (f'static const uint8_t {name}[] PROGMEM = {{\n  ' + ',\n  '.join(rows) + '\n};\n'
            f'static const size_t {name}_LEN = sizeof({name});\n')


def unpack_header(text):
    """Returns {name: bytes} for the arrays in a generated header (used by check.py)."""
    out = {}
    for name, body in re.findall(r'static const uint8_t (\w+)\[\] PROGMEM = \{(.*?)\};', text, re.S):
        out[name] = gzip.decompress(bytes(int(x, 16) for x in re.findall(r'0x([0-9a-f]{2})', body)))
    return out


def main():
    page, en = html(), english()
    out = ROOT / 'src/webui_html.h'
    out.write_text('// Generated by tools/webui_build.py from src/webui.html and tools/webui_en.py.\n'
                   '// Do not edit; run: python3 tools/webui_build.py\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n\n'
                   + array('WEBUI_GZ', pack(page)) + '\n' + array('WEBUI_EN_GZ', pack(en)))
    print(f'{out}: page {len(page.encode())} -> {len(pack(page))} B, English {len(en.encode())} -> {len(pack(en))} B')


if __name__ == '__main__':
    main()
